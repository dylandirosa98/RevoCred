#!/usr/bin/env python3
"""Generate the mock-only reviewed evidence mirror; Go JSON is authoritative."""
from pathlib import Path
import argparse
root = Path(__file__).resolve().parents[1]
source = root / 'revocred-api/internal/valuation/benefits.json'
target = root / 'revocred_flutter/lib/core/data/reviewed_benefits.dart'
text = "// Generated by scripts/sync_ongoing_evidence.py; do not edit.\nconst reviewedBenefitsJson = r'''" + source.read_text() + "''';\n"
parser = argparse.ArgumentParser()
parser.add_argument('--check', action='store_true')
args = parser.parse_args()
if args.check:
    assert target.read_text() == text, 'Reviewed benefit mirror differs; regenerate it'
else:
    target.write_text(text)
print('Reviewed benefit mirror matches' if args.check else 'Generated reviewed benefit mirror')
